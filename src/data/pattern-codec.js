/* §2 패턴 문자열 ↔ 숫자 배열 변환
   pulse16-mk16.html 에서 분리. 클래식 스크립트라 최상위 선언은
   전역 렉시컬 스코프를 공유한다 — 로드 순서가 곧 의존 순서다. */
'use strict';

/* ═══ §2  프리셋 데이터 ═════════════════════════════════════
   패턴 문자열은 16자 고정. X=강세, x=보통, -=없음.
   bass 는 스케일 degree(0~7), -=쉼표.

   자료 검증 후 수정 이력
     Trap      : 킥 tight + 튠 -1 (짧고 높게), 저역은 808 전담
     D&B       : 스네어 7·15 고스트, 햇 8분 뒷박, 174 BPM
     Reggaeton : 구 Dembow. 96 BPM은 레게톤 범위이므로 개명
                 스네어 3·6·11·14 (3·6·10·13 오기 수정)
     Afrobeats : 구 Afrobeat. 프로그래밍 드럼 구성이므로 복수형이 맞음
   ═════════════════════════════════════════════════════════ */

/* 트랙이 늘어나도 기존 프리셋을 전부 고칠 필요가 없도록,
   해당 트랙의 패턴이 없으면 빈 패턴으로 친다. (perc 트랙 신설 때문) */
const pat  = s => s ? [...s].map(c => c==='X' ? 2 : c==='x' ? 1 : 0)
                    : new Array(STEPS).fill(0);
const bpat = s => [...s].map(c => c==='-' ? -1 : +c);

/* ── 화성 문자열 → 스텝별 비트마스크 ──
   '0'~'7' : 그 음도를 근음으로 한 3화음 (인덱스 r, r+2, r+4)
   'a'~'h' : 단음 (아르페지오용, a=0도 … h=7도)
   '-'     : 쉼

   7음계에서는 인덱스 7 이 0 의 옥타브 위라, 8 이상은 7 을 빼면
   같은 음이름의 한 옥타브 아래가 된다 — 자리바꿈으로 처리한다.
   펜타토닉(5음)에서는 r,r+2,r+4 가 근음·4도·b7 이 되어
   3화음이 아니라 4도 쌓기 화음이 된다. 힙합·록에서는 오히려 이쪽이 맞다. */
const TRIAD = r => {
  let m=0;
  for(const o of [0,2,4]){ let i=r+o; if(i>7) i-=7; m |= 1<<i; }
  return m;
};
/* ═══ 대중음악 화음표 (CHORD) ═══════════════════════════════════
   값은 **근음으로부터의 도수 오프셋**입니다. 반음이 아닙니다 —
   그래서 화음의 «성질»(장·단·감)은 스케일이 알아서 정합니다.
   Natural Minor 의 0도에 sev 를 얹으면 i-m7, 2도에 얹으면 III-maj7 이
   저절로 나옵니다. 이 설계 덕에 화음 종류표가 스케일 수만큼 안 늘어납니다.

   보이싱은 «실제로 치는 모양» 을 따랐습니다:
     nine     1-3-7-9   — **5도를 뺍니다.** 5도를 남기면 다섯 음이 뭉쳐
                          저역이 탁해집니다. 실제 피아노 보이싱도 뺍니다.
     add9     1-3-5-9   — 7음이 없는 것이 add9 의 정의입니다. 5도는 남깁니다.
     eleven   1-3-7-11  — 9도를 생략한 형태가 실제 보이싱입니다.
     thirteen 1-3-7-13  — 9·11 을 생략합니다. 다 쌓으면 여섯 음이라 안 씁니다.
     power    1-5       — 3도가 없어 장단이 정해지지 않습니다. 록·메탈.
     sus2/4   3도를 2도·4도로 갈아 끼웁니다. 긴장을 남기는 화음입니다. */
const CHORD = {
  triad   : [0,2,4],       // 1-3-5   기본 3화음
  power   : [0,4],         // 1-5     록·메탈
  sus2    : [0,1,4],       // 1-2-5
  sus4    : [0,3,4],       // 1-4-5   EDM·가스펠·록
  six     : [0,2,4,5],     // 1-3-5-6 시티팝·재즈
  sev     : [0,2,4,6],     // 1-3-5-7 R&B·재즈·소울의 기본
  nine    : [0,2,6,8],     // 1-3-7-9 네오소울·시티팝
  add9    : [0,2,4,8],     // 1-3-5-9 K-pop·시티팝
  eleven  : [0,2,6,10],    // 1-3-7-11
  thirteen: [0,2,6,12],    // 1-3-7-13
};
/* ── 5음계 전용 모양 ──────────────────────────────────────────
   ⚠ **도수 오프셋은 7음계를 전제합니다.** 5음계는 도수 간격이 달라
     같은 오프셋이 전혀 다른 음정이 됩니다:

       5음계 도수  0→근음  1→단3도  2→완전4도  3→완전5도  4→단7도

   그래서 그대로 쓰면 이런 일이 납니다(실측):
     power [0,4]  → 근음 + **단7도**.  파워코드인데 5도가 없습니다.
     sus4  [0,3,4]→ 근음 + 5도 + b7.  4도가 없습니다.
     add9  [0,2,4,8] → 9도 자리에 **5도의 옥타브 위**가 옵니다.

   5음계에 장2도(9도)가 아예 없으므로 add9·sus2 는 성립하지 않습니다 —
   3화음(4도 쌓기)으로 되돌립니다. power·sus4 는 도수를 고쳐 잡습니다.

   ⚠ triad 는 **일부러 안 고칩니다.** 5음계의 «4도 쌓기» 는 힙합·록에서
     오히려 정확한 소리이고(위 CHORD 주석), 프리셋 357개가 이미 그 소리입니다.
   ⚠ sev·nine 도 그대로 둡니다 — 5음계에서 b7 과 #9 가 나와
     블루스·펑크 어법(7#9)에 맞습니다. */
const CHORD_PENTA = {
  power   : [0,3],      // 1-5
  sus4    : [0,2,3],    // 1-4-5
  sus2    : [0,2,3],    // 장2도가 없다 → sus4 로 대신한다
  add9    : [0,2,4],    // 9도가 없다 → 3화음
  eleven  : [0,2,4],
  thirteen: [0,2,4],
  six     : [0,2,3,4],  // 1-4-5-b7 (5음계의 6도는 없다)
};
const CHORD_NAMES = Object.keys(CHORD);
/* 근음 0~6 + 최대 오프셋 12 = 18. 렌더 루프는 이 값까지 훑어야 한다. */
const DEG_MAX = 19;

/** 근음 도수 r 에 화음 종류 type 을 얹어 비트마스크로.

    ⚠ triad 는 **예전 TRIAD() 를 그대로 씁니다**(7 을 넘으면 −7 자리바꿈).
      기존 프리셋 357개가 전부 '0'~'7' 로 적혀 있으므로, 여기가 달라지면
      전 프리셋의 소리가 바뀝니다. 확장 화음만 자리바꿈 없이 위로 쌓습니다 —
      9도를 옥타브 안으로 접으면 근음과 장2도로 부딪혀 뭉치기 때문입니다. */
function chordMask(r, type, scaleName){
  if(type==='triad' || !CHORD[type]) return TRIAD(r);
  const penta = (typeof SCALE_N!=='undefined') && SCALE_N[scaleName] === 5;
  const shape = (penta && CHORD_PENTA[type]) || CHORD[type];
  const n = penta ? 5 : 7;
  const root = ((r % n) + n) % n;                 // 확장 화음은 근음을 옥타브 안으로
  let m = 0;
  for(const o of shape) m |= 1 << (root + o);
  return m;
}

/** 화음 마스크 → 반음 배열. **보이싱을 두 옥타브 안으로 접습니다.**

    왜 필요한가: 도수 오프셋은 스케일 크기에 따라 실제 음정이 달라집니다.
    7음계에서 «12도 위» 는 1.7옥타브지만, 5음계(펜타토닉)에서는 2.4옥타브입니다.
    그대로 쌓았더니 펜타토닉 13화음이 근음에서 **28반음(2.3옥타브)** 까지
    벌어졌습니다(실측). 실제 건반 보이싱은 그렇게 안 칩니다 — 위 음을
    한 옥타브 내려 잡습니다.

    ⚠ 3화음은 어떤 스케일에서도 최대 17반음이라 이 가지에 **절대 안 걸립니다.**
      그래서 기존 프리셋의 소리는 한 비트도 안 바뀝니다(테스트로 확인). */
function chordVoicing(mask, scaleName){
  const out = [];
  let lo = null;
  for(let d=0; d<DEG_MAX; d++) if(mask & (1<<d)){
    let v = degSemi(d, scaleName);
    if(lo === null) lo = v;
    /* 문턱 21 = 진짜 13도(장6도+옥타브). 그보다 넓어지는 것만 접는다 —
       7음계의 정상적인 13화음은 딱 21반음이라 그대로 두고, 5음계에서
       24~28반음까지 벌어지던 것만 잡힌다. 3화음은 최대 17반음이라 무관. */
    while(v - lo > 21) v -= 12;
    out.push(v);
  }
  return out;
}

/* ── 건반 표기 ────────────────────────────────────────────────
     -        쉼
     0~7      화음 — 그 도수를 근음으로. **종류는 기본 타입이 정합니다**
              (하위분기가 배정. 안 정하면 3화음 = 예전과 동일)
     a~h      단음 (0~7도)
   ── 아래는 «이 자리만 다른 화음» 을 쓰고 싶을 때의 명시 표기 ──
     A~H      7화음      I~P      9화음      Q~X      add9
     i~p      sus4       q~x      6화음

   16자 고정 폭을 지켜야 해서 한 글자에 «도수 + 종류» 를 함께 담았습니다.
   기본 타입으로 덮이는 것이 대부분이라, 명시 표기는 예외용입니다. */
const KPAT_EXPLICIT = [
  ['A','H','sev'], ['I','P','nine'], ['Q','X','add9'],
  ['i','p','sus4'], ['q','x','six'],
];
const kpat = (s, type, scaleName) => s
  ? [...s].map(c => {
      if(c==='-') return 0;
      if(c>='0' && c<='7') return chordMask(+c, type || 'triad', scaleName);
      for(const [lo,hi,t] of KPAT_EXPLICIT)
        if(c>=lo && c<=hi) return chordMask(c.charCodeAt(0)-lo.charCodeAt(0), t, scaleName);
      const d=c.charCodeAt(0)-97;               // 'a' → 0
      return (d>=0 && d<8) ? (1<<d) : 0;
    })
  : new Array(STEPS).fill(0);
