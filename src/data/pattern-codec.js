/* ═══ §2  프리셋 데이터 ═════════════════════════════════════
   패턴 문자열은 16자 고정. X=강세, x=보통, -=없음.
   bass 는 스케일 degree(0~7), -=쉼표.

   자료 검증 후 수정 이력
     Trap      : 킥 tight + 튠 -1 (짧고 높게), 저역은 808 전담
     D&B       : 스네어 7·15 고스트, 햇 8분 뒷박, 174 BPM
     Reggaeton : 구 Dembow. 96 BPM은 레게톤 범위이므로 개명
                 스네어 3·6·11·14 (3·6·10·13 오기 수정)
     Afrobeats : 구 Afrobeat. 프로그래밍 드럼 구성이므로 복수형이 맞음
   ═════════════════════════════════════════════════════════ */

/* 트랙이 늘어나도 기존 프리셋을 전부 고칠 필요가 없도록,
   해당 트랙의 패턴이 없으면 빈 패턴으로 친다. (perc 트랙 신설 때문) */
const pat  = s => s ? [...s].map(c => c==='X' ? 2 : c==='x' ? 1 : 0)
                    : new Array(STEPS).fill(0);
const bpat = s => [...s].map(c => c==='-' ? -1 : +c);

/* ── 화성 문자열 → 스텝별 비트마스크 ──
   '0'~'7' : 그 음도를 근음으로 한 3화음 (인덱스 r, r+2, r+4)
   'a'~'h' : 단음 (아르페지오용, a=0도 … h=7도)
   '-'     : 쉼

   7음계에서는 인덱스 7 이 0 의 옥타브 위라, 8 이상은 7 을 빼면
   같은 음이름의 한 옥타브 아래가 된다 — 자리바꿈으로 처리한다.
   펜타토닉(5음)에서는 r,r+2,r+4 가 근음·4도·b7 이 되어
   3화음이 아니라 4도 쌓기 화음이 된다. 힙합·록에서는 오히려 이쪽이 맞다. */
const TRIAD = r => {
  let m=0;
  for(const o of [0,2,4]){ let i=r+o; if(i>7) i-=7; m |= 1<<i; }
  return m;
};
const kpat = s => s
  ? [...s].map(c => {
      if(c==='-') return 0;
      if(c>='0' && c<='7') return TRIAD(+c);
      const d=c.charCodeAt(0)-97;               // 'a' → 0
      return (d>=0 && d<8) ? (1<<d) : 0;
    })
  : new Array(STEPS).fill(0);
